#!/usr/bin/env node

/**
 * D1-D3: DB/Mock 데이터 단일 소스화 - Git Hooks Setup
 * 
 * Purpose: 개발 환경에 pre-commit hook을 설치하여 
 * 로컬에서 데이터 일관성을 자동으로 검증합니다.
 */

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const colors = {
  red: '\x1b[31m',
  green: '\x1b[32m',
  yellow: '\x1b[33m',
  blue: '\x1b[34m',
  cyan: '\x1b[36m',
  reset: '\x1b[0m'
};

function log(color, message) {
  console.log(`${colors[color]}${message}${colors.reset}`);
}

function setupGitHooks() {
  log('cyan', '🔧 Setting up Git hooks for D1-D3 data consistency...\n');
  
  try {
    // Find git root directory
    const gitRoot = execSync('git rev-parse --show-toplevel', { encoding: 'utf8' }).trim();
    const hooksDir = path.join(gitRoot, '.git', 'hooks');
    
    // Check if .git directory exists
    if (!fs.existsSync(hooksDir)) {
      log('red', '❌ Git hooks directory not found. Are you in a Git repository?');
      process.exit(1);
    }
    
    // Pre-commit hook setup
    const preCommitHookPath = path.join(hooksDir, 'pre-commit');
    const preCommitScriptPath = path.join(__dirname, 'pre-commit-hook.sh');
    
    // Check if pre-commit script exists
    if (!fs.existsSync(preCommitScriptPath)) {
      log('red', '❌ Pre-commit hook script not found at:', preCommitScriptPath);
      process.exit(1);
    }
    
    // Create pre-commit hook
    const hookContent = `#!/bin/bash
# D1-D3: DB/Mock 데이터 단일 소스화 - Pre-commit Hook
# Auto-generated by setup-git-hooks.js

SCRIPT_DIR="$( cd "$( dirname "\${BASH_SOURCE[0]}" )" && pwd )"
PROJECT_ROOT="$(git rev-parse --show-toplevel)"

# Execute the pre-commit hook script
exec "\${PROJECT_ROOT}/apps/api/scripts/pre-commit-hook.sh"
`;
    
    fs.writeFileSync(preCommitHookPath, hookContent, { mode: 0o755 });
    log('green', '✅ Pre-commit hook installed successfully');
    
    // Make the hook script executable (Unix systems)
    if (process.platform !== 'win32') {
      try {
        execSync(`chmod +x "${preCommitHookPath}"`);
        execSync(`chmod +x "${preCommitScriptPath}"`);
        log('green', '✅ Hook scripts made executable');
      } catch (error) {
        log('yellow', '⚠️  Could not make scripts executable. You may need to run:');
        log('yellow', `   chmod +x "${preCommitHookPath}"`);
        log('yellow', `   chmod +x "${preCommitScriptPath}"`);
      }
    }
    
    // Test hook installation
    log('blue', '🧪 Testing hook installation...');
    
    try {
      // Create a test file to trigger the hook
      const testFile = path.join(process.cwd(), 'test-hook.tmp');
      fs.writeFileSync(testFile, 'test');
      
      // Stage the test file
      execSync(`git add "${testFile}"`);
      
      // Check if hook would run (dry run)
      const hookExists = fs.existsSync(preCommitHookPath);
      const hookExecutable = (fs.statSync(preCommitHookPath).mode & 0o100) !== 0;
      
      // Clean up test file
      execSync(`git reset HEAD "${testFile}"`);
      fs.unlinkSync(testFile);
      
      if (hookExists && hookExecutable) {
        log('green', '✅ Hook installation test passed');
      } else {
        log('yellow', '⚠️  Hook may not be properly executable');
      }
      
    } catch (error) {
      log('yellow', '⚠️  Could not test hook installation:', error.message);
    }
    
    log('cyan', '\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━');
    log('green', '🎉 Git hooks setup completed successfully!');
    log('cyan', '\nWhat happens now:');
    log('cyan', '• Pre-commit hook will run before each commit');
    log('cyan', '• Data consistency will be validated automatically'); 
    log('cyan', '• Mock data will be synced from seed.ts if needed');
    log('cyan', '• Commits will be blocked if validation fails');
    log('cyan', '\nTo test the hook:');
    log('cyan', '1. Make changes to apps/api/prisma/seed.ts');
    log('cyan', '2. Run: git add . && git commit -m "test"');
    log('cyan', '3. Watch the automatic sync and validation!');
    log('cyan', '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n');
    
  } catch (error) {
    log('red', '❌ Failed to setup Git hooks:', error.message);
    process.exit(1);
  }
}

// Run setup if called directly
if (require.main === module) {
  setupGitHooks();
}

module.exports = { setupGitHooks };