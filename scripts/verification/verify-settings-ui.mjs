import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const base = process.env.BASE_URL || 'http://127.0.0.1:3000';
const out = process.env.VERIFICATION_OUTPUT || path.resolve('docs/verification/2026-11-17');
await fs.mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE_PATH ? { executablePath: process.env.BROWSER_EXECUTABLE_PATH } : {}), args: ['--no-sandbox'] });
const report = { name: 'settings', runAt: new Date().toISOString(), status: 'FAIL', checks: [], pageErrors: [] };
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
page.on('pageerror', error => report.pageErrors.push(error.message));
const email = `verify.staff.${Date.now()}@test.example`;
let createdId;
try {
  await page.goto(`${base}/login`);
  await page.getByLabel('회사 선택').selectOption('j1');
  await page.getByLabel('역할 선택').selectOption('admin');
  await page.getByRole('button', { name: '로그인', exact: true }).click();
  await page.waitForURL(url => !url.pathname.includes('/login'));
  await page.goto(`${base}/settings`);
  await page.getByRole('heading', { name: '설정', exact: true }).waitFor();
  await page.getByRole('button', { name: '직원 추가', exact: true }).click();
  let dialog = page.getByRole('dialog', { name: '직원 추가', exact: true });
  await dialog.getByLabel('이름', { exact: true }).fill('검증 직원');
  await dialog.getByLabel('이메일', { exact: true }).fill(email);
  await dialog.getByLabel('부서', { exact: true }).fill('운영팀');
  await dialog.getByLabel('초기 비밀번호', { exact: true }).fill('Verification123!');
  const createResponse = page.waitForResponse(response => response.url().endsWith('/api/v2/users') && response.request().method() === 'POST');
  await dialog.getByRole('button', { name: '저장', exact: true }).click();
  createdId = (await (await createResponse).json()).id;
  assert.ok(createdId);
  const row = page.getByRole('row').filter({ hasText: email });
  await row.getByText('검증 직원', { exact: true }).waitFor();
  report.checks.push('J1 demo company/admin login and actual employee creation through UI');
  await row.getByRole('button', { name: '편집', exact: true }).click();
  dialog = page.getByRole('dialog', { name: '직원 편집', exact: true });
  await dialog.getByLabel('이름', { exact: true }).fill('검증 직원 수정');
  await dialog.getByLabel('부서', { exact: true }).fill('예약팀');
  await dialog.getByLabel('권한', { exact: true }).selectOption('MANAGER');
  await dialog.getByRole('button', { name: '저장', exact: true }).click();
  await row.getByText('검증 직원 수정', { exact: true }).waitFor();
  await row.getByText('매니저', { exact: true }).waitFor();
  const persisted = await page.request.get(`${base}/api/v2/users/${createdId}`);
  assert.equal(persisted.status(), 200);
  assert.deepEqual(Object.fromEntries(Object.entries(await persisted.json()).filter(([key]) => ['name', 'department', 'role', 'companyCode'].includes(key))), { name: '검증 직원 수정', department: '예약팀', role: 'MANAGER', companyCode: 'j1' });
  report.checks.push('Name, department and role edit persisted in API');
  page.once('dialog', async popup => popup.accept());
  await row.getByRole('button', { name: '비활성화', exact: true }).click();
  await row.getByText('비활성', { exact: true }).waitFor();
  const blocked = await browser.newContext();
  const denied = await blocked.request.post(`${base}/api/v2/auth/login`, { data: { companyCode: 'j1', email, password: 'Verification123!' } });
  assert.equal(denied.status(), 401);
  await blocked.close();
  report.checks.push('Deactivation persists and rejects subsequent authentication');
  page.once('dialog', async popup => popup.accept());
  await row.getByRole('button', { name: '재활성화', exact: true }).click();
  await row.getByText('활성', { exact: true }).waitFor();
  const active = await page.request.get(`${base}/api/v2/users/${createdId}`);
  assert.equal(active.status(), 200); assert.equal((await active.json()).isActive, true);
  report.checks.push('Reactivation restores the existing employee');
  await page.screenshot({ path: path.join(out, 'settings-employees.png'), fullPage: true });
  assert.deepEqual(report.pageErrors, []);
  report.status = 'PASS';
} catch (error) {
  report.error = error.stack || String(error); process.exitCode = 1;
} finally {
  if (createdId) await page.request.delete(`${base}/api/v2/users/${createdId}`).catch(() => {});
  await fs.writeFile(path.join(out, 'settings-report.json'), JSON.stringify(report, null, 2));
  await browser.close(); console.log(JSON.stringify(report));
}
