import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const base = process.env.BASE_URL || 'http://127.0.0.1:3000';
const out = process.env.VERIFICATION_OUTPUT || path.resolve('docs/verification/2026-11-17');
await fs.mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE_PATH ? { executablePath: process.env.BROWSER_EXECUTABLE_PATH } : {}), args: ['--no-sandbox'] });
const report = { name: 'messaging', runAt: new Date().toISOString(), checks: [], pageErrors: [], status: 'FAIL' };
const check = name => report.checks.push(name);
async function login(company, role) {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  page.on('pageerror', error => report.pageErrors.push(error.message));
  await page.goto(`${base}/login`);
  await page.getByLabel('회사 선택').selectOption(company);
  await page.getByLabel('역할 선택').selectOption(role);
  await page.getByRole('button', { name: '로그인', exact: true }).click();
  await page.waitForURL(url => !url.pathname.includes('/login'));
  await page.goto(`${base}/chat`);
  await page.getByRole('heading', { name: '메신저', exact: true }).waitFor();
  await page.getByText('실시간 연결됨', { exact: true }).waitFor({ timeout: 20000 });
  return { page, context };
}
try {
  const admin = await login('entrip', 'admin');
  const manager = await login('entrip', 'manager');
  check('Two independent demo users logged in through UI with cookie sessions');
  await admin.page.getByRole('button', { name: '조직도', exact: true }).click();
  const row = admin.page.locator('aside').getByText('manager@entrip.com', { exact: false }).locator('../..');
  await row.getByRole('button', { name: '1:1 대화' }).waitFor();
  const created = admin.page.waitForResponse(response => response.url().endsWith('/api/v2/messages/conversations') && response.request().method() === 'POST');
  await row.getByRole('button', { name: '1:1 대화' }).click();
  const room = (await (await created).json()).id;
  assert.ok(room);
  await admin.page.getByRole('textbox', { name: '메시지', exact: true }).waitFor();
  check('Organization directory creates a persisted direct conversation');
  const first = `메신저 실시간 검증 ${Date.now()}`;
  await admin.page.getByRole('textbox', { name: '메시지', exact: true }).fill(first);
  const start = Date.now();
  await admin.page.getByRole('button', { name: '전송', exact: true }).click();
  const received = manager.page.locator('aside').getByRole('button').filter({ hasText: first });
  await received.waitFor({ timeout: 7000 });
  report.receiveMilliseconds = Date.now() - start;
  assert.ok(report.receiveMilliseconds < 7000, 'Realtime delivery must precede 15-second polling fallback');
  await received.click();
  await manager.page.locator('main p').getByText(first, { exact: true }).waitFor();
  const reply = `검증 회신 ${Date.now()}`;
  await manager.page.getByRole('textbox', { name: '메시지', exact: true }).fill(reply);
  await manager.page.getByRole('button', { name: '전송', exact: true }).click();
  await admin.page.locator('main p').getByText(reply, { exact: true }).waitFor({ timeout: 7000 });
  check('Both directions deliver real persisted messages over realtime transport');
  await admin.page.getByRole('button', { name: '직원 초대', exact: true }).click();
  const invited = admin.page.locator('aside').getByText('user@entrip.com', { exact: false }).locator('../..');
  await invited.getByRole('button', { name: '초대', exact: true }).click();
  await admin.page.getByText('참여자 3명', { exact: true }).waitFor();
  const third = await login('entrip', 'user');
  await third.page.locator('aside').getByRole('button').filter({ hasText: reply }).click();
  await third.page.locator('main p').getByText(first, { exact: true }).waitFor();
  const history = await third.page.request.get(`${base}/api/v2/messages/conversations/${room}/messages`);
  assert.equal(history.status(), 200); assert.ok((await history.json()).some(message => message.content === reply));
  check('Third employee is invited into the same room and sees its persisted history');
  await admin.page.evaluate(() => { localStorage.clear(); sessionStorage.clear(); });
  await admin.page.reload();
  await admin.page.getByRole('heading', { name: '메신저', exact: true }).waitFor();
  await admin.page.locator('aside').getByRole('button').filter({ hasText: reply }).click();
  await admin.page.locator('main p').getByText(first, { exact: true }).waitFor();
  check('Cookie-only reload restores conversation without localStorage tokens');
  const other = await login('j1', 'admin');
  await other.page.getByRole('button', { name: '조직도', exact: true }).click();
  assert.equal(await other.page.locator('aside').getByText('admin@entrip.com', { exact: false }).count(), 0);
  const forbidden = await other.page.request.get(`${base}/api/v2/messages/conversations/${room}/messages`);
  assert.equal(forbidden.status(), 404);
  check('J1 directory and conversation access are isolated from Entrip');
  await admin.page.screenshot({ path: path.join(out, 'messaging-admin.png'), fullPage: true });
  await manager.page.screenshot({ path: path.join(out, 'messaging-reply.png'), fullPage: true });
  await admin.page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await admin.page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
  await admin.page.screenshot({ path: path.join(out, 'messaging-mobile.png'), fullPage: true });
  check('Mobile viewport remains within 390px');
  assert.deepEqual(report.pageErrors, []);
  report.status = 'PASS';
} catch (error) {
  report.error = error.stack || String(error);
  process.exitCode = 1;
} finally {
  await fs.writeFile(path.join(out, 'messaging-report.json'), JSON.stringify(report, null, 2));
  await browser.close();
  console.log(JSON.stringify(report));
}
