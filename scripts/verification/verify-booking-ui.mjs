import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
const require = createRequire(new URL('../../apps/web/package.json', import.meta.url));
const { chromium } = require('@playwright/test');
const baseURL = process.env.BASE_URL || 'http://127.0.0.1:3000';
const output = process.env.VERIFICATION_OUTPUT || path.resolve('docs/verification/2026-11-17');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE_PATH ? { executablePath: process.env.BROWSER_EXECUTABLE_PATH } : {}), args: ['--no-sandbox', '--disable-dev-shm-usage'] });
const context = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('dialog', dialog => dialog.accept());
const report = { status: 'RUNNING', checks: [], screenshots: [], baseURL, startedAt: new Date().toISOString() };
let createdId;
const screenshot = async name => { const filename = `${name}.png`; await page.screenshot({ path: path.join(output, filename), fullPage: true }); report.screenshots.push(filename); };
const waitForWrite = method => page.waitForResponse(response => response.url().includes('/api/v2/bookings') && response.request().method() === method && response.status() >= 200 && response.status() < 300);
try {
  const login = await context.request.post('/api/v2/auth/login', { data: { email: 'admin@entrip.com', password: 'pass1234', companyCode: 'entrip' } });
  assert.equal(login.status(), 200, await login.text());
  await page.goto('/calendar-monthly');
  await page.getByRole('heading', { name: '월간 캘린더', exact: true }).waitFor();
  const day = await page.getByRole('button', { name: /^\d{4}-\d{2}-\d{2} 예약 등록$/ }).first().getAttribute('aria-label');
  assert.ok(day);
  await page.getByRole('button', { name: day, exact: true }).click();
  let editor = page.getByRole('dialog', { name: '새 예약 등록', exact: true });
  const selectedDate = day.slice(0, 10);
  assert.equal(await editor.getByLabel('출발일 *', { exact: true }).inputValue(), selectedDate);
  assert.equal(await editor.getByLabel('귀국일 *', { exact: true }).inputValue(), selectedDate);
  const name = `예약 UI 검증 ${Date.now()}`;
  await editor.getByLabel('팀명 *', { exact: true }).fill(name);
  await editor.getByLabel('출발지 *', { exact: true }).fill('부산');
  await editor.getByLabel('목적지 *', { exact: true }).fill('삿포로');
  await editor.getByLabel('고객명', { exact: true }).fill('검증 고객');
  await editor.getByLabel('대표자', { exact: true }).fill('검증 대표');
  await editor.getByLabel('연락처', { exact: true }).fill('010-2345-6789');
  await editor.getByLabel('이메일', { exact: true }).fill('booking-verify@example.com');
  await editor.getByLabel('인원 *', { exact: true }).fill('4');
  await editor.getByLabel('예약 상태', { exact: true }).selectOption('CONFIRMED');
  await editor.getByLabel('판매금액', { exact: true }).fill('3000000');
  await editor.getByLabel('입금액', { exact: true }).fill('500000');
  await editor.getByRole('button', { name: '+ 호텔 추가', exact: true }).click();
  await editor.getByLabel('호텔명', { exact: true }).nth(0).fill('도야 호텔');
  await editor.getByLabel('호텔 수량', { exact: true }).nth(0).fill('2');
  await editor.getByLabel('호텔 단가', { exact: true }).nth(0).fill('12000');
  await editor.getByLabel('호텔 통화', { exact: true }).nth(0).selectOption('JPY');
  await editor.getByRole('button', { name: '+ 호텔 추가', exact: true }).click();
  await editor.getByLabel('호텔명', { exact: true }).nth(1).fill('삿포로 호텔');
  await editor.getByLabel('호텔 단가', { exact: true }).nth(1).fill('16000');
  await editor.getByRole('button', { name: '+ 항공 추가', exact: true }).click();
  await editor.getByLabel('항공명', { exact: true }).fill('부산-신치토세');
  await editor.getByLabel('항공 수량', { exact: true }).fill('4');
  await editor.getByLabel('항공 단가', { exact: true }).fill('450000');
  const createResponse = waitForWrite('POST');
  await editor.getByRole('button', { name: '예약 저장', exact: true }).click();
  createdId = (await (await createResponse).json()).data.id;
  editor = page.getByRole('dialog', { name: '예약 수정', exact: true });
  await editor.getByText('변경 사항 없음', { exact: true }).waitFor();
  let detail = await (await context.request.get(`/api/v2/bookings/${createdId}`)).json();
  assert.equal(detail.data.contact, '010-2345-6789');
  assert.equal(detail.data.status, 'CONFIRMED');
  assert.equal(detail.data.hotelInfo.length, 2);
  assert.equal(detail.data.flightInfo[0].quantity, 4);
  assert.equal(detail.data.hotelInfo[0].currency, 'JPY');
  report.checks.push('date-cell create; customer contacts, repeated hotels/flights, status, deposit persisted in real API');
  await editor.getByRole('button', { name: '변경 이력', exact: true }).click();
  await editor.getByRole('heading', { name: '저장된 변경 이력' }).waitFor();
  await editor.getByText('생성', { exact: true }).waitFor();
  const popupPromise = page.waitForEvent('popup');
  await editor.getByRole('button', { name: '인쇄', exact: true }).click();
  const popup = await popupPromise;
  await popup.getByRole('heading', { name: name, exact: true }).waitFor();
  assert.ok((await popup.textContent('body')).includes('도야 호텔'));
  await popup.screenshot({ path: path.join(output, 'booking-print.png'), fullPage: true });
  report.screenshots.push('booking-print.png');
  await popup.close();
  report.checks.push('print popup and persisted create history');
  await screenshot('booking-desktop');
  await editor.getByLabel('연락처', { exact: true }).fill('010-9999-8888');
  await page.reload();
  editor = page.getByRole('dialog', { name: '예약 수정', exact: true });
  await editor.waitFor();
  assert.equal(await editor.getByLabel('연락처', { exact: true }).inputValue(), '010-9999-8888');
  assert.equal(await editor.getByLabel('호텔명', { exact: true }).nth(1).inputValue(), '삿포로 호텔');
  report.checks.push('draft and repeated detail rows survive full reload in their workspace tab');
  const updateResponse = waitForWrite('PUT');
  await editor.getByRole('button', { name: '예약 저장', exact: true }).click();
  await updateResponse;
  await editor.getByText('변경 사항 없음', { exact: true }).waitFor();
  detail = await (await context.request.get(`/api/v2/bookings/${createdId}`)).json();
  assert.equal(detail.data.contact, '010-9999-8888');
  assert.equal(detail.data.version, 2);
  assert.equal(detail.data.history.length, 2);
  report.checks.push('versioned edit and actual history persisted');
  await page.setViewportSize({ width: 390, height: 844 });
  await editor.getByLabel('호텔 단가', { exact: true }).nth(0).scrollIntoViewIfNeeded();
  await editor.getByLabel('호텔 단가', { exact: true }).nth(0).fill('14000');
  const mobileUpdate = waitForWrite('PUT');
  await editor.getByRole('button', { name: '예약 저장', exact: true }).click();
  await mobileUpdate;
  await editor.getByText('변경 사항 없음', { exact: true }).waitFor();
  const box = await editor.boundingBox();
  assert.ok(box && box.x >= -1 && box.x + box.width <= 391, JSON.stringify(box));
  await screenshot('booking-mobile');
  report.checks.push('390px editor fits viewport; repeated detail price edits persist');
  await editor.getByRole('button', { name: '변경 이력', exact: true }).click();
  const hotelHistory = editor.getByText('호텔 변경 전후 항목 보기', { exact: true }).first();
  await hotelHistory.click();
  const changes = hotelHistory.locator('..');
  assert.ok((await changes.innerText()).includes('12,000'));
  assert.ok((await changes.innerText()).includes('14,000'));
  assert.ok((await changes.innerText()).includes('도야 호텔'));
  await changes.scrollIntoViewIfNeeded();
  await screenshot('booking-history-mobile');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await changes.scrollIntoViewIfNeeded();
  await screenshot('booking-history-desktop');
  report.checks.push('Detailed history displays actual hotel name, currency, quantity and 12,000 to 14,000 price change on mobile and desktop');
  await editor.getByRole('button', { name: '닫기', exact: true }).click();
  await page.setViewportSize({ width: 1440, height: 1000 });
  for (const [route, title] of [['/list-monthly', '월간 목록'], ['/list-weekly', '주간 목록'], ['/calendar-week', '주간 캘린더']]) {
    await page.goto(route);
    await page.getByRole('heading', { name: title, exact: true }).waitFor();
    await page.getByRole('button', { name: '+ 예약 등록', exact: true }).waitFor();
  }
  report.checks.push('month/week list and weekly calendar render shared persisted editor');
  assert.deepEqual(errors, []);
  report.status = 'PASS';
} catch (error) {
  report.status = 'FAIL';
  report.error = error.stack || error.message;
  await screenshot('booking-failure').catch(() => {});
  process.exitCode = 1;
} finally {
  report.pageErrors = errors;
  report.createdBookingId = createdId;
  report.finishedAt = new Date().toISOString();
  await writeFile(path.join(output, 'booking-ui-verification.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
  await browser.close();
}
