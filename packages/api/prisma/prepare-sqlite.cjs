const fs = require('node:fs');
const path = require('node:path');

// Project the same application models into SQLite. Relations and field names
// stay identical, so imported IDs and stored foreign keys remain usable.
const canonical = fs.readFileSync(path.join(__dirname, 'schema.prisma'), 'utf8');
const schema = canonical
  .replace('provider = "postgresql"', 'provider = "sqlite"')
  .replaceAll('@default(cuid())', '@default(uuid())')
  .replace(/^(\s+\w+\s+)String\[\]/gm, '$1Json @default("[]")');
const destination = path.join(__dirname, 'sqlite', 'schema.prisma');
fs.mkdirSync(path.dirname(destination), { recursive: true });
fs.writeFileSync(destination, '// Generated by ../prepare-sqlite.cjs\n' + schema);
